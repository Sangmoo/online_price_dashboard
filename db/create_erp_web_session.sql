GRANT SELECT, INSERT, DELETE         ON T_ERP_WEB_LOGIN_LOG  TO SS10DEV;
GRANT SELECT, INSERT, UPDATE, DELETE ON T_ERP_WEB_AI_CONV    TO SS10DEV;
GRANT SELECT, INSERT, DELETE         ON T_ERP_WEB_AI_FAV     TO SS10DEV;
GRANT SELECT, INSERT, UPDATE, DELETE ON T_ERP_WEB_USER_PREF  TO SS10DEV;
GRANT SELECT ON SQ_ERP_WEB_LOGIN_LOG TO SS10DEV;
GRANT SELECT ON SQ_ERP_WEB_AI_FAV    TO SS10DEV;
CREATE SYNONYM SS10DEV.T_ERP_WEB_SESSION    FOR SS10.T_ERP_WEB_SESSION;
CREATE SYNONYM SS10DEV.T_ERP_WEB_LOGIN_LOCK FOR SS10.T_ERP_WEB_LOGIN_LOCK;
CREATE SYNONYM SS10DEV.T_ERP_WEB_LOGIN_LOG  FOR SS10.T_ERP_WEB_LOGIN_LOG;
CREATE SYNONYM SS10DEV.T_ERP_WEB_AI_CONV    FOR SS10.T_ERP_WEB_AI_CONV;
CREATE SYNONYM SS10DEV.T_ERP_WEB_AI_FAV     FOR SS10.T_ERP_WEB_AI_FAV;
CREATE SYNONYM SS10DEV.T_ERP_WEB_USER_PREF  FOR SS10.T_ERP_WEB_USER_PREF;
CREATE SYNONYM SS10DEV.SQ_ERP_WEB_LOGIN_LOG FOR SS10.SQ_ERP_WEB_LOGIN_LOG;
CREATE SYNONYM SS10DEV.SQ_ERP_WEB_AI_FAV    FOR SS10.SQ_ERP_WEB_AI_FAV;
